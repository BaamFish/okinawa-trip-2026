import fs from 'node:fs/promises';
import {createHash} from 'node:crypto';
const id='1N8ASAmc2JZbwIGBCwwXdeeW64rysBi3X4fRE3a3EMz0';
const saved=JSON.parse(await fs.readFile('src/data/source-reviewed.json','utf8'));
const response=await fetch(`https://docs.google.com/document/d/${id}/export?format=txt`,{redirect:'follow'});
if(!response.ok)throw Error(`Google Docs export HTTP ${response.status}; grant read access or use a local exported TXT file.`);
const raw=(await response.text()).replace(/^\uFEFF/,'');
if(/<!doctype|<html/i.test(raw)||!raw.includes('Day 1')||!raw.includes('Day 4'))throw Error('Export did not return the expected itinerary text. No source files were changed.');
const sensitive=/(?:[A-Z0-9._%+-]+@[A-Z0-9.-]+\.[A-Z]{2,}|(?:電話|手機|訂位代碼|訂位代號|訂單編號|預約編號|護照|API\s*Key|access[_ ]?token)\s*[:：]|gh[pousr]_[A-Za-z0-9]{20,}|github_pat_[A-Za-z0-9_]{20,}|sk-[A-Za-z0-9]{20,})/i;
let redacted=0;
const pageFurniture=['2026 沖繩聖誕旅行｜12/25–12/28','Okinawa Christmas Trip · 行程 / 預算 / 預約資訊'];
const text=raw.split(/\r?\n/).filter(line=>!pageFurniture.includes(line.trim())).map(line=>{if(sensitive.test(line)){redacted++;return '[此行可能含私人資訊，已從候選內容遮罩]'}return line}).join('\n');
const normalize=t=>t.replace(/[\s\u00a0]+/g,' ').trim();
const changed=normalize(text)!==normalize(saved.text);
const candidate={sourceUrl:saved.sourceUrl,fetchedAt:new Date().toISOString(),changed,redactedLines:redacted,sha256:createHash('sha256').update(text).digest('hex'),reviewRequired:true,text};
await fs.mkdir('.sync',{recursive:true});
await fs.writeFile('.sync/source-latest.json',JSON.stringify(candidate,null,2));
const oldLines=new Set(saved.text.split(/\r?\n/).map(x=>x.trim()).filter(Boolean));
const newLines=text.split(/\r?\n/).map(x=>x.trim()).filter(Boolean);
await fs.writeFile('.sync/review.md',`# Google Docs 同步審閱\n\n變更：${changed?'有':'無'}\n可能私人資訊已遮罩行數：${redacted}\n\n## 新增或改寫行\n\n${newLines.filter(x=>!oldLines.has(x)).map(x=>'- '+x).join('\n')||'未發現文字變更。'}\n\n請核對原文件、更新 src/data/itinerary.json 的時段／狀態／導航與 source-reviewed.json；完成隱私檢查後再測試建置及推送。\n`);
console.log(`Source fetched. Changed: ${changed}; redacted lines: ${redacted}. Review .sync/review.md and .sync/source-latest.json. Live data was NOT overwritten or deployed.`);
if(process.argv.includes('--check')&&changed)process.exitCode=1;
